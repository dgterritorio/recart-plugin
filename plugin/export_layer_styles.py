#!/usr/bin/env python3
"""Export public.layer_styles to the portable layer_styles.sql the plugin loads.

Reads the table with psql (libpq service name plus port) and writes a fixed
CREATE TABLE plus one INSERT per row. Catalog and schema are not copied from
the database: every row uses current_database() and the '{schema}' placeholder.
"""

import argparse
import csv
import glob
import io
import os
import re
import shutil
import subprocess
import sys

if __package__:
    from .normalize_style_svg_paths import normalize_svg_paths
else:
    from normalize_style_svg_paths import normalize_svg_paths


CREATE_TABLE = """\
CREATE TABLE IF NOT EXISTS public.layer_styles (
    id integer generated by default as identity NOT NULL PRIMARY KEY,
    f_table_catalog character varying,
    f_table_schema character varying,
    f_table_name character varying,
    f_geometry_column character varying,
    stylename text,
    styleqml xml,
    stylesld xml,
    useasdefault boolean,
    description text,
    owner character varying(63) DEFAULT CURRENT_USER,
    ui xml,
    update_time timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    type character varying
);
"""

# Blank lines kept so a re-export matches the checked-in layer_styles.sql files.
_AFTER_CREATE = "\n" * 7

_INSERT_PREFIX = (
    "INSERT INTO public.layer_styles ( f_table_catalog, f_table_schema, "
    "f_table_name, f_geometry_column, stylename, styleqml, stylesld, "
    "useasdefault, description, type) VALUES ( current_database(), '{schema}', "
)

_COPY_SQL = (
    "COPY ("
    " SELECT f_table_name, f_geometry_column, stylename,"
    " styleqml::text, stylesld::text,"
    " useasdefault::text, description, type"
    " FROM public.layer_styles"
    " ORDER BY id"
    ") TO STDOUT WITH (FORMAT csv, NULL E'\\\\N', FORCE_QUOTE *)"
)

_COPY_TAG = re.compile(r"COPY \d+")
_BOOL = {"true": "true", "false": "false", "t": "true", "f": "false"}
_COLUMN_COUNT = 8


def sql_literal(value):
    """Quote a text value for a PostgreSQL literal. None becomes NULL."""
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def render_boolean(value):
    """Emit an unquoted boolean, or NULL."""
    if value is None:
        return "NULL"
    mapped = _BOOL.get(value)
    if mapped is None:
        raise ValueError("Unexpected useasdefault value: {}".format(value))
    return mapped


def render_insert(row):
    """Render one layer_styles INSERT. ``row`` is the eight exported columns."""
    if len(row) != _COLUMN_COUNT:
        raise ValueError("Expected {} values, got {}".format(_COLUMN_COUNT, len(row)))
    table, geom, name, qml, sld, default, description, geom_type = row
    values = [
        sql_literal(table),
        sql_literal(geom),
        sql_literal(name),
        sql_literal(qml),
        sql_literal(sld),
        render_boolean(default),
        sql_literal(description),
        sql_literal(geom_type),
    ]
    return _INSERT_PREFIX + ", ".join(values) + ");"


def render_sql(rows):
    """Build the SQL file and rewrite absolute SVG paths to relative names."""
    chunks = [CREATE_TABLE, _AFTER_CREATE]
    if rows:
        chunks.append("\n".join(render_insert(row) for row in rows))
        chunks.append("\n")
    return normalize_svg_paths("".join(chunks))


def _strip_copy_tag(text):
    """Drop a trailing ``COPY n`` status line psql may append after the data."""
    stripped = text.rstrip("\r\n")
    head, sep, last = stripped.rpartition("\n")
    if _COPY_TAG.fullmatch(last):
        return head + sep if head else ""
    return text


def _csv_reader(text):
    """CSV reader whose field limit can hold a full QML or SLD document."""
    limit = sys.maxsize
    while True:
        try:
            csv.field_size_limit(limit)
            break
        except OverflowError:
            limit //= 10
    return csv.reader(io.StringIO(text, newline=""))


def parse_copy_csv(text):
    """Parse psql ``COPY ... CSV`` output into rows. ``\\N`` becomes None."""
    if text.startswith("\ufeff"):
        text = text[1:]
    text = _strip_copy_tag(text)
    rows = []
    reader = _csv_reader(text)
    for record in reader:
        if not record:
            continue
        if len(record) != _COLUMN_COUNT:
            preview = ", ".join(record[:3])
            raise ValueError(
                "Expected {} columns from layer_styles, got {} ({})".format(
                    _COLUMN_COUNT, len(record), preview
                )
            )
        rows.append(tuple(None if field == "\\N" else field for field in record))
    return rows


def _psql_version(path):
    """Version number from a PostgreSQL install path, or 0 when it has none."""
    normalized = path.replace("\\", "/")
    match = re.search(
        r"(?:postgresql@|postgresql/|PostgreSQL/)(\d+)",
        normalized,
        re.IGNORECASE,
    )
    if match:
        return int(match.group(1))
    match = re.search(r"/Versions/(\d+)/", normalized, re.IGNORECASE)
    if match:
        return int(match.group(1))
    return 0


def _install_candidates():
    candidates = []
    if sys.platform == "win32":
        for env_name in ("ProgramFiles", "ProgramFiles(x86)"):
            root = os.environ.get(env_name)
            if root:
                pattern = os.path.join(root, "PostgreSQL", "*", "bin", "psql.exe")
                candidates.extend(glob.glob(pattern))
    elif sys.platform == "darwin":
        candidates.extend(glob.glob("/opt/homebrew/opt/postgresql@*/bin/psql"))
        candidates.extend(glob.glob("/usr/local/opt/postgresql@*/bin/psql"))
        candidates.extend(glob.glob("/opt/homebrew/opt/libpq/bin/psql"))
        candidates.extend(glob.glob("/usr/local/opt/libpq/bin/psql"))
        candidates.extend(
            glob.glob("/Applications/Postgres.app/Contents/Versions/*/bin/psql")
        )
    else:
        candidates.extend(glob.glob("/usr/lib/postgresql/*/bin/psql"))
    return [path for path in candidates if os.path.isfile(path)]


def find_psql():
    """Return a psql binary from PATH, or the newest standard install location."""
    found = shutil.which("psql")
    if found:
        return found
    candidates = _install_candidates()
    if not candidates:
        return None
    candidates.sort(key=lambda path: (_psql_version(path), path))
    return candidates[-1]


def fetch_rows(psql, service, port):
    """Run the COPY query and return parsed rows."""
    env = os.environ.copy()
    env["PGCLIENTENCODING"] = "UTF8"
    result = subprocess.run(
        [
            psql,
            "service={}".format(service),
            "-p",
            str(port),
            "-X",
            "-q",
            "-v",
            "ON_ERROR_STOP=1",
            "-c",
            _COPY_SQL,
        ],
        capture_output=True,
        env=env,
        check=False,
    )
    stdout = result.stdout.decode("utf-8")
    stderr = result.stderr.decode("utf-8", errors="replace")
    if result.returncode != 0:
        if stderr:
            sys.stderr.write(stderr)
            if not stderr.endswith("\n"):
                sys.stderr.write("\n")
        raise SystemExit(result.returncode or 1)
    return parse_copy_csv(stdout)


def write_output(path, text):
    """Write ``text`` as UTF-8 with LF newlines, moving an existing file aside."""
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    if os.path.isfile(path):
        if path.endswith(".sql"):
            backup = path[:-4] + ".old.sql"
        else:
            backup = path + ".old.sql"
        os.replace(path, backup)
        print("Existing file moved to {}".format(backup))
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Export public.layer_styles to a portable layer_styles.sql."
    )
    parser.add_argument(
        "-o",
        dest="output",
        default="./layer_styles.sql",
        help="Output SQL path (default: ./layer_styles.sql)",
    )
    parser.add_argument(
        "-p",
        dest="port",
        default="5434",
        help="PostgreSQL port (default: 5434)",
    )
    parser.add_argument("service", help="PostgreSQL service name")
    args = parser.parse_args(argv)

    psql = find_psql()
    if not psql:
        sys.stderr.write(
            "Error: psql not found. Install the PostgreSQL client tools.\n"
        )
        return 1

    rows = fetch_rows(psql, args.service, args.port)
    write_output(args.output, render_sql(rows))
    print(
        "Wrote {} from service={} port={}".format(
            args.output, args.service, args.port
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
